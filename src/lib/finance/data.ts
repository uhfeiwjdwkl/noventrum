export function incomeBySource(transactions: Transaction[], fx: FxMap = {}, base = "USD") {
  const map = new Map<string, number>();
  const cutoff = new Date();
  cutoff.setFullYear(cutoff.getFullYear() - 1);
  for (const t of transactions) {
    if (t.kind !== "income") continue;
    if (new Date(t.date) < cutoff) continue;
    map.set(t.category, (map.get(t.category) ?? 0) + toBase(t.amount, t.currency, fx, base));
  }
  return Array.from(map.entries())
    .map(([source, amount]) => ({ source, amount: Math.round(amount * 100) / 100 }))
    .sort((a, b) => b.amount - a.amount);
}

// ---- payers (income counterparties) ----

export function payerSlug(name: string) {
  return encodeURIComponent(name.trim().toLowerCase());
}

/** Every payer you have ever received income from, with totals. */
export function incomeByPayer(transactions: Transaction[]) {
  const map = new Map<string, { payer: string; total: number; count: number; last: string }>();
  for (const t of transactions) {
    if (t.kind !== "income") continue;
    const key = t.merchant.trim().toLowerCase();
    if (!key) continue;
    const cur = map.get(key) ?? { payer: t.merchant.trim(), total: 0, count: 0, last: t.date };
    cur.total += t.amount;
    cur.count += 1;
    if (t.date > cur.last) cur.last = t.date;
    map.set(key, cur);
  }
  return Array.from(map.values()).sort((a, b) => b.total - a.total);
}

export function payerTransactions(transactions: Transaction[], payer: string) {
  const key = decodeURIComponent(payer).trim().toLowerCase();
  return transactions
    .filter((t) => t.kind === "income" && t.merchant.trim().toLowerCase() === key)
    .sort((a, b) => (a.date < b.date ? 1 : -1));
}

export function monthlyTotals(transactions: Transaction[]) {
  const map = new Map<string, number>();
  for (const t of transactions) map.set(monthKey(t.date), (map.get(monthKey(t.date)) ?? 0) + t.amount);
  return Array.from(map.entries())
    .sort(([a], [b]) => (a < b ? -1 : 1))
    .map(([month, amount]) => ({ month, amount: Math.round(amount * 100) / 100 }));
}

// ---- recurrence ----

export function advance(date: string, every: number, unit: RecurUnit) {
  const d = new Date(`${date}T00:00:00Z`);
  if (unit === "day") d.setUTCDate(d.getUTCDate() + every);
  else if (unit === "week") d.setUTCDate(d.getUTCDate() + every * 7);
  else d.setUTCMonth(d.getUTCMonth() + every);
  return d.toISOString().slice(0, 10);
}

/** Dates a rule should have fired on, up to and including `until`. */
export function dueDates(rule: RecurringRule, until: string): string[] {
  if (!rule.active) return [];
  const out: string[] = [];
  let d = rule.lastRun ? advance(rule.lastRun, rule.every, rule.unit) : rule.startDate;
  let guard = 0;
  while (d <= until && guard++ < 500) {
    if (rule.endDate && d > rule.endDate) break;
    out.push(d);
    d = advance(d, rule.every, rule.unit);
  }
  return out;
}

export function describeRule(rule: RecurringRule) {
  const n = rule.every;
  const unit = n === 1 ? rule.unit : `${rule.unit}s`;
  return n === 1 ? `every ${rule.unit}` : `every ${n} ${unit}`;
}

export function savingsRateSeries(transactions: Transaction[], fx: FxMap = {}, base = "USD", fxHist: FxHistory = {}) {
  return monthlyCashflow(transactions, fx, base, fxHist).map((m) => ({
    month: m.month,
    rate:
      m.income > 0
        ? Math.max(0, Math.round(((m.income - m.expense) / m.income) * 1000) / 10)
        : 0,
  }));
}

export function assetAllocation(
  holdings: Holding[],
  properties: Property[] = [],
  physical: PhysicalAsset[] = [],
  fx: FxMap = {},
  base = "USD",
  accounts: Account[] = [],
) {
  const map = new Map<string, number>();
  for (const h of holdings) {
    const v = toBase(h.shares * h.price, h.currency, fx, base);
    map.set(h.assetClass, (map.get(h.assetClass) ?? 0) + v);
  }
  const fxCash = accounts
    .filter((a) => a.currency !== base && a.balance > 0)
    .reduce((s, a) => s + toBase(a.balance, a.currency, fx, base), 0);
  if (fxCash > 0) map.set("forex", (map.get("forex") ?? 0) + fxCash);
  const pv = propertyValue(properties, fx, base);
  if (pv > 0) map.set("property", pv);
  const ph = physicalValue(physical, fx, base);
  if (ph > 0) map.set("physical", ph);
  return Array.from(map.entries()).map(([k, v]) => ({ name: k, value: Math.round(v) }));
}

/** Currency used when a caller doesn't pass one — kept in sync with settings. */
let displayCurrency = "AUD";
export function setDisplayCurrency(code: string) {
  if (code) displayCurrency = code;
}

export function fmtCurrency(
  n: number,
  opts: { compact?: boolean; currency?: string } = {},
) {
  const currency = opts.currency ?? displayCurrency;
  const safe = (c: string) => {
    try {
      new Intl.NumberFormat("en-US", { style: "currency", currency: c }).format(1);
      return c;
    } catch {
      return "USD";
    }
  };
  const cur = safe(currency);
  if (!isFinite(n))
    return new Intl.NumberFormat("en-US", { style: "currency", currency: cur, maximumFractionDigits: 0 }).format(0);
  if (opts.compact && Math.abs(n) >= 1000) {
    const abs = Math.abs(n);
    const sign = n < 0 ? "-" : "";
    const sym =
      new Intl.NumberFormat("en-US", { style: "currency", currency: cur, maximumFractionDigits: 0 })
        .formatToParts(0)
        .find((p) => p.type === "currency")?.value ?? "$";
    if (abs >= 1_000_000) return `${sign}${sym}${(abs / 1_000_000).toFixed(1)}M`;
    if (abs >= 1_000) return `${sign}${sym}${(abs / 1_000).toFixed(1)}K`;
  }
  return new Intl.NumberFormat("en-US", {
    style: "currency",
    currency: cur,
    maximumFractionDigits: 2,
  }).format(n);
}
export function fmtPct(n: number) {
  if (!isFinite(n)) return "0.00%";
  return `${n >= 0 ? "+" : ""}${n.toFixed(2)}%`;
}

// ---- trade-derived holdings ----

export interface SymbolMeta {
  name?: string;
  assetClass?: AssetClass;
  currency?: string;
  sector?: string;
}

/**
 * Holdings are never entered by hand — they are the running result of the
 * trade ledger. Average-cost basis in both the asset's currency and the base
 * currency (using the FX rate stored on each trade), so realized P/L includes
 * currency gain or loss.
 */
export function deriveHoldings(
  trades: Trade[],
  prev: Holding[] = [],
  meta: Record<string, SymbolMeta> = {},
): Holding[] {
  const sorted = [...trades]
    .filter((t) => t.assetClass !== "forex")
    .sort((a, b) => (a.date === b.date ? 0 : a.date < b.date ? -1 : 1));
  const acc = new Map<
    string,
    {
      shares: number;
      cost: number;
      costBase: number;
      realized: number;
      realizedBase: number;
      last: number;
      currency?: string;
    }
  >();

  for (const t of sorted) {
    const sym = t.symbol.toUpperCase();
    const cur =
      acc.get(sym) ??
      {
        shares: 0,
        cost: 0,
        costBase: 0,
        realized: 0,
        realizedBase: 0,
        last: t.price,
        currency: t.currency,
      };
    const extra = (t.fees || 0) + (t.tax ?? 0);
    const rate = t.fxRate && t.fxRate > 0 ? t.fxRate : 1;
    if (t.side === "buy") {
      cur.shares += t.shares;
      cur.cost += t.shares * t.price + extra;
      cur.costBase += (t.shares * t.price + extra) * rate;
    } else {
      const avg = cur.shares > 0 ? cur.cost / cur.shares : t.price;
      const avgBase = cur.shares > 0 ? cur.costBase / cur.shares : t.price * rate;
      const qty = Math.min(t.shares, cur.shares);
      cur.realized += qty * (t.price - avg) - extra;
      cur.realizedBase += (qty * t.price - extra) * rate - qty * avgBase;
      cur.shares = Math.max(0, cur.shares - t.shares);
      cur.cost = Math.max(0, cur.cost - qty * avg);
      cur.costBase = Math.max(0, cur.costBase - qty * avgBase);
    }
    cur.last = t.price;
    cur.currency = t.currency ?? cur.currency;
    acc.set(sym, cur);
  }

  const out: Holding[] = [];
  for (const [symbol, v] of acc) {
    const old = prev.find((h) => h.symbol === symbol);
    const m = meta[symbol] ?? {};
    out.push({
      id: old?.id ?? symbol,
      symbol,
      name: m.name || old?.name || symbol,
      assetClass: m.assetClass ?? old?.assetClass ?? "stock",
      shares: Math.round(v.shares * 1e8) / 1e8,
      avgCost: v.shares > 0 ? v.cost / v.shares : 0,
      avgCostBase: v.shares > 0 ? v.costBase / v.shares : 0,
      price: old?.price && old.price > 0 ? old.price : v.last,
      dayChangePct: old?.dayChangePct ?? 0,
      sector: m.sector ?? old?.sector,
      currency: m.currency ?? old?.currency ?? v.currency,
      priceUpdatedAt: old?.priceUpdatedAt,
      realized: Math.round(v.realized * 100) / 100,
      realizedBase: Math.round(v.realizedBase * 100) / 100,
      history: old?.history ?? [],
    });
  }
  return out.filter((h) => h.shares > 0.00000001 || (h.realizedBase ?? 0) !== 0);
}

/** Shares of `symbol` held on (or before) an ISO date, from the ledger. */
export function sharesAt(trades: Trade[], symbol: string, date: string) {
  let shares = 0;
  for (const t of trades) {
    if (t.assetClass === "forex") continue;
    if (t.symbol.toUpperCase() !== symbol.toUpperCase()) continue;
    if (t.date > date) continue;
    shares += t.side === "buy" ? t.shares : -t.shares;
  }
  return Math.max(0, shares);
}

/** Historical close for a symbol at/just before a date, falling back to live price. */
export function priceAt(holding: Holding, date: string) {
  const pt = [...holding.history].reverse().find((p) => p.date <= date);
  return pt?.price ?? holding.price;
}

/** Portfolio market value at any past date: ledger shares × historical close. */
export function portfolioValueAt(
  holdings: Holding[],
  trades: Trade[],
  date: string,
  fx: FxMap = {},
  base = "USD",
  fxHist: FxHistory = {},
) {
  let total = 0;
  for (const h of holdings) {
    const q = sharesAt(trades, h.symbol, date);
    if (q <= 0) continue;
    total += q * priceAt(h, date) * rateAtMonth(h.currency, date.slice(0, 7), fxHist, fx, base);
  }
  return total;
}

/** Realized P/L booked across all closed positions, in base currency. */
export function realizedPL(holdings: Holding[]) {
  return holdings.reduce((s, h) => s + (h.realizedBase ?? h.realized ?? 0), 0);
}
