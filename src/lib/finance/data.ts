// ---- currency ----

export type FxMap = Record<string, number> & { __base?: string };
/** Historical rates keyed `CUR:YYYY-MM` -> value of 1 CUR in base. */
export type FxHistory = Record<string, number>;

/** Value of 1 unit of `cur` expressed in the base currency. */
export function rateOf(cur: string | undefined, fx: FxMap, base: string): number {
  if (!cur || cur === base) return 1;
  const r = fx[cur];
  return typeof r === "number" && isFinite(r) && r > 0 ? r : 1;
}

/** Convert an amount into the base currency using live rates. */
export function toBase(
  amount: number,
  cur: string | undefined,
  fx: FxMap,
  base: string,
): number {
  return amount * rateOf(cur, fx, base);
}

export function convert(
  amount: number,
  from: string | undefined,
  to: string,
  fxRates: FxMap,
): number {
  if (!from || from === to) return amount;
  if (fxRates.__base === to) return amount * rateOf(from, fxRates, to);
  const key = `${from}${to}`;
  if (fxRates[key]) return amount * fxRates[key];
  return amount;
}

/** Historical rate for a month, falling back to the live rate. */
export function rateAtMonth(
  cur: string | undefined,
  month: string,
  hist: FxHistory,
  fx: FxMap,
  base: string,
): number {
  if (!cur || cur === base) return 1;
  const h = hist[`${cur}:${month}`];
  if (typeof h === "number" && h > 0) return h;
  return rateOf(cur, fx, base);
}

// ---- derived metrics (pure) ----

export function totalAssets(accounts: Account[], fx: FxMap = {}, base = "USD") {
  return accounts
    .filter((a) => a.balance > 0)
    .reduce((s, a) => s + toBase(a.balance, a.currency, fx, base), 0);
}
export function totalLiabilities(accounts: Account[], fx: FxMap = {}, base = "USD") {
  return -accounts
    .filter((a) => a.balance < 0)
    .reduce((s, a) => s + toBase(a.balance, a.currency, fx, base), 0);
}
export function netWorth(accounts: Account[], fx: FxMap = {}, base = "USD") {
  return totalAssets(accounts, fx, base) - totalLiabilities(accounts, fx, base);
}

/** Account balance at a date, inferred around the confirmed balance anchor. */
export function accountBalanceAt(account: Account, transactions: Transaction[], date: string) {
  const anchor = account.balanceDate ?? new Date().toISOString().slice(0, 10);
  const ledger = transactions.filter((t) => t.accountId === account.id);
  if (date < anchor) {
    return account.balance - ledger
      .filter((t) => t.date > date && t.date <= anchor)
      .reduce((sum, t) => sum + t.amount, 0);
  }
  return account.balance + ledger
    .filter((t) => t.date > anchor && t.date <= date)
    .reduce((sum, t) => sum + t.amount, 0);
}

/** Cash held in currencies other than the base one, valued in base. */
export function currencyPositions(accounts: Account[], fx: FxMap = {}, base = "USD") {
  return accounts
    .filter((a) => a.currency !== base && a.balance !== 0)
    .map((a) => ({
      account: a,
      rate: rateOf(a.currency, fx, base),
      valueBase: toBase(a.balance, a.currency, fx, base),
    }));
}

export function portfolioValue(holdings: Holding[], fx: FxMap = {}, base = "USD") {
  return holdings.reduce((s, h) => s + toBase(h.shares * h.price, h.currency, fx, base), 0);
}
/** Cost basis in base currency, using the FX rate in force at each trade. */
export function portfolioCost(holdings: Holding[]) {
  return holdings.reduce((s, h) => s + h.shares * (h.avgCostBase || h.avgCost), 0);
}
export function propertyValue(properties: Property[], fx: FxMap = {}, base = "USD") {
  return properties
    .filter((p) => !p.soldDate)
    .reduce((s, p) => s + toBase(p.currentValue, p.currency, fx, base), 0);
}
export function physicalValue(assets: PhysicalAsset[], fx: FxMap = {}, base = "USD") {
  return assets
    .filter((a) => !a.soldDate)
    .reduce((s, a) => s + toBase(a.currentValue, a.currency, fx, base), 0);
}

/** Total net worth including holdings, real estate and physical assets. */
export function totalNetWorth(
  accounts: Account[],
  holdings: Holding[],
  properties: Property[],
  physical: PhysicalAsset[],
  fx: FxMap = {},
  base = "USD",
) {
  return (
    netWorth(accounts, fx, base) +
    portfolioValue(holdings, fx, base) +
    propertyValue(properties, fx, base) +
    physicalValue(physical, fx, base)
  );
}

export function monthKey(d: string) {
  return d.slice(0, 7);
}

export function monthlyCashflow(
  transactions: Transaction[],
  fx: FxMap = {},
  base = "USD",
  fxHist: FxHistory = {},
) {
  const map = new Map<string, { income: number; expense: number }>();
  const today = new Date().toISOString().slice(0, 10);
  for (const t of transactions) {
    if (t.kind !== "income" && t.kind !== "expense") continue;
    if (t.date > today) continue;
    const k = monthKey(t.date);
    const cur = map.get(k) ?? { income: 0, expense: 0 };
    const amount = t.amount * rateAtMonth(t.currency, k, fxHist, fx, base);
    if (amount > 0) cur.income += amount;
    else cur.expense += -amount;
    map.set(k, cur);
  }
  return Array.from(map.entries())
    .sort(([a], [b]) => (a < b ? -1 : 1))
    .map(([month, v]) => ({ month, ...v, net: v.income - v.expense }));
}

/**
 * Back-calculate net-worth month by month from transactions + holdings
 * historical prices + property/physical valuations. No manual snapshots.
 */
export function netWorthSeries(
  accounts: Account[],
  transactions: Transaction[],
  holdings: Holding[] = [],
  properties: Property[] = [],
  physical: PhysicalAsset[] = [],
  trades: Trade[] = [],
  fx: FxMap = {},
  base = "USD",
  fxHist: FxHistory = {},
): { month: string; value: number }[] {
  const now = totalNetWorth(accounts, holdings, properties, physical, fx, base);
  const cf = monthlyCashflow(transactions, fx, base, fxHist);
  if (cf.length === 0) return [];

  const monthPortfolio = (month: string) => {
    const asOf = `${month}-31`;
    let total = 0;
    for (const h of holdings) {
      const shares = trades.length ? sharesAt(trades, h.symbol, asOf) : h.shares;
      if (shares <= 0) continue;
      const pt = [...h.history].reverse().find((p) => p.date.slice(0, 7) <= month);
      const native = shares * (pt?.price ?? h.price);
      total += native * rateAtMonth(h.currency, month, fxHist, fx, base);
    }
    return total;
  };

  const monthProperty = (month: string) => {
    let total = 0;
    for (const p of properties) {
      if (p.purchaseDate.slice(0, 7) > month) continue;
      if (p.soldDate && p.soldDate.slice(0, 7) < month) continue;
      const v = [...p.valuations].reverse().find((x) => x.date.slice(0, 7) <= month);
      total += (v?.value ?? p.currentValue) * rateAtMonth(p.currency, month, fxHist, fx, base);
    }
    return total;
  };
  const monthPhysical = (month: string) => {
    let total = 0;
    for (const a of physical) {
      if (a.purchaseDate.slice(0, 7) > month) continue;
      if (a.soldDate && a.soldDate.slice(0, 7) < month) continue;
      total += a.currentValue * rateAtMonth(a.currency, month, fxHist, fx, base);
    }
    return total;
  };

  const series: { month: string; value: number }[] = [];
  let cash = netWorth(accounts, fx, base);
  for (let i = cf.length - 1; i >= 0; i--) {
    const m = cf[i].month;
    const val = cash + monthPortfolio(m) + monthProperty(m) + monthPhysical(m);
    series.unshift({ month: m, value: Math.round(val) });
    cash -= cf[i].net;
  }
  if (series.length)
    series[series.length - 1] = {
      month: series[series.length - 1].month,
      value: Math.round(now),
    };
  return series;
}

export function spendingByCategory(transactions: Transaction[], days = 30, fx: FxMap = {}, base = "USD") {
  const map = new Map<string, number>();
  const cutoff = new Date();
  cutoff.setDate(cutoff.getDate() - days);
  for (const t of transactions) {
    if (t.kind !== "expense") continue;
    if (new Date(t.date) < cutoff) continue;
    map.set(t.category, (map.get(t.category) ?? 0) + -toBase(t.amount, t.currency, fx, base));
  }
  return Array.from(map.entries())
    .map(([category, amount]) => ({ category, amount: Math.round(amount * 100) / 100 }))
    .sort((a, b) => b.amount - a.amount);
}

